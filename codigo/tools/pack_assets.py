#!/usr/bin/env python3
"""Compile shared offline PNG resources into small native RGB555/4bpp arrays.

Developer-only dependency: Pillow. The generated C++ and PC resources are
included in releases; consoles and the PC server need no image libraries.
"""
import argparse
import json
from pathlib import Path
import shutil
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[1]
parser = argparse.ArgumentParser()
parser.add_argument("--font", default="/usr/share/fonts/truetype/dejavu/DejaVuSansMono.ttf")
args = parser.parse_args()
assets = ROOT / "assets/pksm"
mapping = json.loads((assets / "sprites.json").read_text())
atlas = Image.open(assets / "sprites.png").convert("RGBA")
web = ROOT / "server/web/assets"
web.mkdir(exist_ok=True, parents=True)
for p in assets.glob("*"):
    if p.suffix in (".png", ".json"):
        shutil.copyfile(p, web / p.name)


def color555(r, g, b):
    return 0x8000 | (r >> 3) | (g >> 3) << 5 | (b >> 3) << 10


def array(name, kind, values):
    out = "const " + kind + " " + name + "[] = {\n"
    for i in range(0, len(values), 24):
        out += ",".join(map(str, values[i:i + 24])) + ",\n"
    return out + "};\n"


out = """// Generated by tools/pack_assets.py from bundled offline resources.
// Visual resources adapted from PKSM/FlagBrew; see THIRD_PARTY.md.
#include "graphics_assets.hpp"
#include "pokemon.hpp"
namespace gui::assets {
"""
for name, file in [("top", "bg_top"), ("bottom", "bg_bottom"), ("bar", "bar"),
                   ("button", "button"), ("back", "back"), ("wireless", "wireless"), ("pointer", "pointer")]:
    im = Image.open(assets / (file + ".png")).convert("RGBA")
    out += array(name + "Pixels", "uint16_t", [color555(r, g, b) if a >= 128 else 0 for r, g, b, a in im.getdata()])
    out += f"const Image {name} = {{{im.width},{im.height},{name}Pixels}};\n"
font = ImageFont.truetype(args.font, 11)
out += "const uint8_t font[224][12] = {\n"
for ch in range(32, 256):
    im = Image.new("L", (8, 12))
    ImageDraw.Draw(im).text((0, -1), ("♀" if ch == 128 else "♂" if ch == 129 else chr(ch)), font=font, fill=255)
    out += "{" + ",".join(str(sum((1 << x) for x in range(8) if im.getpixel((x, y)) >= 96)) for y in range(12)) + "},\n"
out += "};\n"
small = ImageFont.truetype(args.font, 9)
out += "const uint8_t fontSmall[224][10] = {\n"
for ch in range(32, 256):
    im = Image.new("L", (6, 10))
    ImageDraw.Draw(im).text((0, -1), ("♀" if ch == 128 else "♂" if ch == 129 else chr(ch)), font=small, fill=255)
    out += "{" + ",".join(str(sum((1 << x) for x in range(6) if im.getpixel((x, y)) >= 80)) for y in range(10)) + "},\n"
out += "};\n"
palettes, packed = [], []
for i in range(mapping["count"]):
    im = atlas.crop(((i % 32) * 34, (i // 32) * 30, (i % 32 + 1) * 34, (i // 32 + 1) * 30))
    rgb = im.convert("RGB").quantize(colors=15, method=Image.Quantize.MEDIANCUT, dither=Image.Dither.NONE)
    palette = rgb.getpalette()
    palette = palette + [0] * max(0, 45 - len(palette))
    palettes.extend([0] + [color555(*palette[j * 3:j * 3 + 3]) for j in range(15)])
    pixels = [p + 1 if a >= 128 else 0 for p, (_, _, _, a) in zip(rgb.getdata(), im.getdata())]
    packed.extend(pixels[j] | pixels[j + 1] << 4 for j in range(0, len(pixels), 2))
out += array("spritePalette", "uint16_t", palettes)
out += array("spritePixels", "uint8_t", packed)
out += f"const unsigned spriteCount = {mapping['count']};\n}}\nnamespace chestlink {{\n"
out += "unsigned pokemonSprite(unsigned species,unsigned form,unsigned generation,bool egg) {\n"
out += f"if(egg)return {mapping['egg']};\n"
# Explicit form entries can be added without changing the decoder or wire format.
for key, value in sorted(mapping.items()):
    if ":" in key:
        gen, species, form = key.split(":")
        out += f"if(generation=={gen} && species=={species} && form=={form})return {value};\n"
out += "(void)form;(void)generation;return species<=898?species:0;\n}\n}\n"
(ROOT / "source/graphics_assets.cpp").write_text(out)
print("Generated native resources:", len(packed), "sprite bytes,", len(palettes) * 2, "palette bytes")
